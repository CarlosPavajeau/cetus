#!/usr/bin/env node
// Generates the console's DIVIPOLA catalog (departments and municipalities with their DANE codes) from the
// official dataset on datos.gov.co. The catalog rarely changes: run this again only when DANE publishes changes.
//
//   node scripts/divipola.mjs && pnpm --filter @cetus/console format
import { writeFile } from "node:fs/promises";

const SOURCE = "https://www.datos.gov.co/resource/gdxc-w37w.json?$limit=5000";
const OUTPUT = new URL("../apps/console/src/features/setup/divipola.ts", import.meta.url);

// Words that stay in lower case inside a name, as in "San José de Cúcuta".
const minorWords = new Set(["de", "del", "la", "las", "los", "el", "y", "e"]);

/** DANE publishes names in upper case: "SAN JOSÉ DE CÚCUTA" becomes "San José de Cúcuta". */
function titleCase(name) {
  return name
    .toLocaleLowerCase("es-CO")
    .split(/(\s+|-|\()/)
    .map((word, index) =>
      index > 0 && minorWords.has(word)
        ? word
        : word.charAt(0).toLocaleUpperCase("es-CO") + word.slice(1),
    )
    .join("")
    .replace(/\bD\.c\./g, "D.C.");
}

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`datos.gov.co answered ${response.status}`);
}
const rows = await response.json();

const departments = new Map();
for (const row of rows) {
  const department = departments.get(row.cod_dpto) ?? {
    code: row.cod_dpto,
    name: titleCase(row.dpto),
    municipalities: [],
  };
  department.municipalities.push({ code: row.cod_mpio, name: titleCase(row.nom_mpio) });
  departments.set(row.cod_dpto, department);
}

const byName = (a, b) => a.name.localeCompare(b.name, "es-CO");
const catalog = [...departments.values()].sort(byName);
for (const department of catalog) {
  department.municipalities.sort(byName);
}

const municipalities = catalog.reduce((count, department) => count + department.municipalities.length, 0);
const source = `// Generated by scripts/divipola.mjs from the DANE DIVIPOLA dataset (datos.gov.co). Do not edit by hand.

export type Municipality = { code: string; name: string };

export type Department = { code: string; name: string; municipalities: Municipality[] };

/** ${catalog.length} departments and ${municipalities} municipalities, sorted by name. */
export const departments: Department[] = ${JSON.stringify(catalog)};
`;
await writeFile(OUTPUT, source);
console.log(`Wrote ${catalog.length} departments and ${municipalities} municipalities to ${OUTPUT.pathname}`);
